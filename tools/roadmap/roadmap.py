#!/usr/bin/env python3
"""Writes docs/roadmap.md from requirements.py and the live issues of all
NepFleet repositories. Run from the repo root: python3 tools/roadmap/roadmap.py
(needs an authenticated gh). Exit code 1 lists requirements whose issue is missing."""
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from requirements import R  # noqa: E402

OWNER = "Serraniel"
REPOS = ["nepfleet", "nepfleet-ui", "nepfleet-templates", "neptide"]
root = Path(__file__).resolve().parents[2]
issues = {}
for repo in REPOS:
    out = subprocess.run(["gh", "issue", "list", "-R", f"{OWNER}/{repo}", "--state", "all", "--limit", "500",
                          "--json", "number,title,state,milestone"], capture_output=True, text=True, check=True).stdout
    for i in json.loads(out):
        issues[(repo, i["title"])] = i

missing = []
lines = [
    "# Roadmap",
    "",
    "Every requirement is linked to the issues that deliver it. ✅ marks a closed issue and ⬜ an open one, with its milestone in brackets. This file is generated by `tools/roadmap/roadmap.py`; do not edit it by hand.",
    "",
    "Milestones: [nepfleet](https://github.com/Serraniel/nepfleet/milestones) · "
    "[nepfleet-ui](https://github.com/Serraniel/nepfleet-ui/milestones) · "
    "[nepfleet-templates](https://github.com/Serraniel/nepfleet-templates/milestones) · "
    "[neptide](https://github.com/Serraniel/neptide/milestones)",
]
area = None
for a, req, refs in R:
    if a != area:
        lines += ["", f"## {a}", "", "| Requirement | Delivered by |", "|---|---|"]
        area = a
    cells = []
    for repo, title in refs:
        if repo == "doc":
            link = title.removeprefix("docs/")  # roadmap.md lives in docs/
            cells.append(f"📄 [{Path(title.split('#')[0]).name}]({link})")
            continue
        i = issues.get((repo, title))
        if i is None:
            missing.append((repo, title))
            cells.append(f"❓ {title}")
            continue
        mark = "✅" if i["state"] == "CLOSED" else "⬜"
        ms = f" ({i['milestone']['title'].split()[0]})" if i.get("milestone") else ""
        cells.append(f"{mark} [{repo}#{i['number']}](https://github.com/{OWNER}/{repo}/issues/{i['number']}){ms}")
    lines.append(f"| {req} | {' · '.join(cells)} |")
(root / "docs/roadmap.md").write_text("\n".join(lines) + "\n")
for m in missing:
    print("missing issue:", *m, file=sys.stderr)
sys.exit(1 if missing else 0)
