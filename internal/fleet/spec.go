// Fleet is fleet.yaml.
type Fleet struct {
	APIVersion string `yaml:"apiVersion" schema:"required;const=nepfleet/v1alpha1"`
	Kind       string `yaml:"kind" schema:"required;const=Fleet"`
	Metadata   struct {
		Name string `yaml:"name" schema:"required;pattern=^[a-z0-9]([a-z0-9_-]{0,61}[a-z0-9])?$"`
	} `yaml:"metadata" schema:"required"`
	Spec Spec `yaml:"spec"`

	Dir string `yaml:"-"`
}

// Spec holds the settings that apply to every stack.
type Spec struct {
	TemplateSources []Source `yaml:"templateSources"`
	Secrets         struct {
		// Age recipients (public keys) that every secret file is encrypted to.
		Age []string `yaml:"age"`
	} `yaml:"secrets"`
	// Notifications: channels (shoutrrr URLs) and routes that pick which
	// events go where (docs/notifications.md).
	Notifications struct {
		Channels map[string]NotifyChannel `yaml:"channels"`
		Routes   []NotifyRoute            `yaml:"routes"`
	} `yaml:"notifications"`
	// UptimeKuma instances get maintenance windows while stacks with their
	// monitors are being changed (docs/maintenance.md).
	UptimeKuma []KumaInstance `yaml:"uptimeKuma"`
	Updates    struct {
		Images string `yaml:"images" schema:"enum=off|notify|auto;default=notify"`
		Host   string `yaml:"host" schema:"enum=off|notify|auto;default=off"`
	} `yaml:"updates"`
	// IngressNetwork is the external network Caddy and the stacks share.
	IngressNetwork string `yaml:"ingressNetwork" schema:"default=nepfleet_ingress"`
	// Paths names host folders that stacks share (a media share, a folder
	// one app writes and another reads). Path inputs refer to them as @name.
	Paths map[string]string `yaml:"paths"`
	// Mirrors are git URLs of second remotes the fleet repository is pushed
	// to (nepfleet mirror), so it survives the loss of its main remote.
	Mirrors []string `yaml:"mirrors"`
	// TZ is passed to stacks as ${TZ}.
	TZ string `yaml:"tz" schema:"default=UTC"`
	// Logging is the log driver of every service that sets none itself, so
	// container logs rotate instead of filling the disk.
	Logging *Logging `yaml:"logging"`
	// Egress: hosts the containers must not reach (known telemetry by
	// default, see TelemetryHosts).
	Egress *Egress `yaml:"egress"`
}

// NotifyChannel is one notification destination.
type NotifyChannel struct {
	// URLSecret names the key in fleet.secret.yaml holding the shoutrrr URL
	// (it contains tokens).
	URLSecret string `yaml:"urlSecret"`
	// URL is a shoutrrr URL written here: only for URLs without secrets.
	URL string `yaml:"url"`
	// Format json sends the raw event to a generic webhook.
	Format string `yaml:"format" schema:"enum=text|json;default=text"`
	// SigningSecret names the key in fleet.secret.yaml with the HMAC key that
	// signs json webhooks (X-NepFleet-Signature).
	SigningSecret string `yaml:"signingSecret"`
}

// NotifyRoute sends matching events to channels.
type NotifyRoute struct {
	Channels []string `yaml:"channels" schema:"required"`
	// Events are names or patterns ("*", "apply.*"); empty matches all.
	Events []string `yaml:"events"`
	// Stacks limits the route to these stacks; empty matches all.
	Stacks      []string `yaml:"stacks"`
	MinSeverity string   `yaml:"minSeverity" schema:"enum=info|warning|error"`
}

// KumaInstance is an Uptime Kuma NepFleet may open maintenance windows in.
type KumaInstance struct {
	Name     string `yaml:"name" schema:"required"`
	URL      string `yaml:"url" schema:"required"`
	Username string `yaml:"username"`
	// PasswordSecret names the key in fleet.secret.yaml holding the password.
	PasswordSecret string `yaml:"passwordSecret"`
	// RollingUpdates: what a swarm update whose monitored services all run
	// two or more replicas gets, as it degrades rather than stops them: a
	// warning incident on the status pages showing them, a maintenance
	// window as for other updates, or nothing.
	RollingUpdates string `yaml:"rollingUpdates" schema:"enum=incident|maintenance|none;default=incident"`
}

// APIVersion is the only version of fleet.yaml and stack.yaml so far.
const APIVersion = "nepfleet/v1alpha1"

// SchemaRef is the git ref the schema links in written files point to.
// Release builds set it to their tag, so files written by v0.1.0 keep
// validating against v0.1.0's schemas whatever happens on main.
var SchemaRef = "main"

// SchemaURL is where the JSON Schema file (e.g. stack.schema.json) of
// SchemaRef is published: schemas/ in this repository, generated by
// go run ./tools/schema.
func SchemaURL(file string) string {
	return "https://raw.githubusercontent.com/Serraniel/nepfleet/" + SchemaRef + "/schemas/" + file
}

// Modeline is the first line of files NepFleet writes: it gives editors
// autocompletion and validation.
func Modeline(file string) string {
	return "# yaml-language-server: $schema=" + SchemaURL(file) + "\n"
}

// FleetSecretsFile holds fleet-wide secrets (SOPS-encrypted).
const FleetSecretsFile = "fleet.secret.yaml"

// SchemaExtend adds the url-or-path rule to the generated schema.
func (*Source) SchemaExtend(s map[string]any) {
	s["oneOf"] = []any{
		map[string]any{"required": []string{"url"}},
		map[string]any{"required": []string{"path"}},
	}
}

// Source is a template catalogue: a git repository or a local directory.
type Source struct {
	Name string `yaml:"name" schema:"required;pattern=^[a-z0-9]([a-z0-9_-]{0,61}[a-z0-9])?$"`
	URL  string `yaml:"url"`
	Ref  string `yaml:"ref"`
	// Path is a local directory, relative to the fleet repository.
	Path string `yaml:"path"`
}

// Stack is stacks/<name>/stack.yaml (or system/<name>/stack.yaml).
type Stack struct {
	APIVersion string `yaml:"apiVersion" schema:"required;const=nepfleet/v1alpha1"`
	Kind       string `yaml:"kind" schema:"required;const=Stack"`
	Metadata   struct {
		Name string `yaml:"name" schema:"required;pattern=^[a-z0-9]([a-z0-9_-]{0,61}[a-z0-9])?$"`
	} `yaml:"metadata" schema:"required"`
	Spec StackSpec `yaml:"spec" schema:"required"`

	// Dir is the stack's directory inside the fleet repository.
	Dir string `yaml:"-"`
}

// StackSpec says where and how a stack runs.
type StackSpec struct {
	Target   string       `yaml:"target" schema:"required"`
	Mode     string       `yaml:"mode" schema:"enum=compose|swarm;default=compose"` // compose | swarm
	Apply    string       `yaml:"apply" schema:"enum=manual|auto;default=manual"`   // manual | auto
	Template *TemplateRef `yaml:"template"`
	// Values are template inputs (or env variables of a plain stack): a
	// literal, or {from: <stack>, value|secret: <name>} to use another
	// stack's value or secret.
	Values  map[string]Value `yaml:"values"`
	Updates string           `yaml:"updates" schema:"enum=off|notify|auto;default=notify"` // off | notify | auto
	// Logging overrides the fleet's default log settings for this stack.
	Logging *Logging `yaml:"logging"`
	// Egress: hosts the containers must not reach (known telemetry by
	// default, see TelemetryHosts).
	Egress *Egress `yaml:"egress"`
	// Snapshot: auto copies the volumes before an apply that recreates
	// running services and restores them on rollback; off skips that.
	Snapshot string `yaml:"snapshot" schema:"enum=auto|off;default=auto"`
	// SnapshotExclude lists mount paths in the containers never copied.
	SnapshotExclude []string `yaml:"snapshotExclude"`
}

// Logging is a compose logging section applied to services without one.
type Logging struct {
	// Enabled: false keeps the daemon's defaults (no logging section added).
	Enabled *bool `yaml:"enabled"`
	// Driver is a Docker log driver, e.g. json-file or local.
	Driver string `yaml:"driver" schema:"default=json-file"`
	// Options are the driver's options, e.g. max-size and max-file.
	Options map[string]string `yaml:"options"`
}

// DefaultLogging rotates json-file logs at 20 MB, keeping 5 files: logs
// stay readable by docker logs, Dozzle and file-based collectors.
var DefaultLogging = Logging{Driver: "json-file", Options: map[string]string{"max-size": "20m", "max-file": "5"}}

// EffectiveLogging merges the stack's setting over the fleet's over the
// default, field by field; nil when logging defaults are switched off.
// json-file without options gets the default rotation, so a setting that
// only names the driver never turns rotation off.
func EffectiveLogging(f *Fleet, s *Stack) *Logging {
	l := Logging{Driver: DefaultLogging.Driver}
	enabled := true
	for _, layer := range []*Logging{fleetLogging(f), stackLogging(s)} {
		if layer == nil {
			continue
		}
		if layer.Enabled != nil {
			enabled = *layer.Enabled
		}
		if layer.Driver != "" && layer.Driver != l.Driver {
			l.Driver, l.Options = layer.Driver, nil // options belong to a driver
		}
		for k, v := range layer.Options {
			if l.Options == nil {
				l.Options = map[string]string{}
			}
			l.Options[k] = v
		}
	}
	if !enabled {
		return nil
	}
	if l.Driver == "json-file" && len(l.Options) == 0 {
		l.Options = DefaultLogging.Options // local rotates by itself
	}
	return &l
}

func fleetLogging(f *Fleet) *Logging {
	if f == nil {
		return nil
	}
	return f.Spec.Logging
}

func stackLogging(s *Stack) *Logging {
	if s == nil {
		return nil
	}
	return s.Spec.Logging
}

// Rotates reports whether l limits log size: json-file needs max-size,
// local rotates by default, other drivers send logs away.
func (l *Logging) Rotates() bool {
	return l != nil && (l.Driver != "json-file" || l.Options["max-size"] != "")
}

// TemplateRef selects a template from a source.
type TemplateRef struct {
	Source  string `yaml:"source" schema:"required"`
	Name    string `yaml:"name" schema:"required"`
	Version string `yaml:"version"`
}

// SecretsFile is the encrypted values file next to stack.yaml.
const SecretsFile = "values.secret.yaml"

// ValidName reports whether s is a valid stack or source name.
func ValidName(s string) bool { return nameRe.MatchString(s) }

// Values Validate accepts; the schema tags must list the same (spec_test.go).
var (
	modes          = []string{"compose", "swarm"}
	applyPolicies  = []string{"manual", "auto"}
	updatePolicies = []string{"off", "notify", "auto"}
	snapshotModes  = []string{"auto", "off"}
)

var nameRe = regexp.MustCompile(`^[a-z0-9]([a-z0-9_-]{0,61}[a-z0-9])?$`) // Compose project names allow _

func decodeStrict(path string, out any) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	dec := yaml.NewDecoder(bytes.NewReader(raw))
	dec.KnownFields(true)
	if err := dec.Decode(out); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

// Load reads fleet.yaml from dir and applies defaults.
func Load(dir string) (*Fleet, error) {
	var f Fleet
	if err := decodeStrict(filepath.Join(dir, "fleet.yaml"), &f); err != nil {
		return nil, err
	}
	f.Dir = dir
	if f.Kind != "Fleet" {
		return nil, fmt.Errorf("fleet.yaml: kind must be Fleet")
	}
	if f.APIVersion != APIVersion {
		return nil, fmt.Errorf("fleet.yaml: apiVersion must be %q, got %q", APIVersion, f.APIVersion)
	}
	if !nameRe.MatchString(f.Metadata.Name) {
		return nil, fmt.Errorf("fleet.yaml: metadata.name %q must be lowercase letters, digits, - and _", f.Metadata.Name)
	}
	if f.Spec.IngressNetwork == "" {
		f.Spec.IngressNetwork = "nepfleet_ingress"
	}
	if f.Spec.TZ == "" {
		f.Spec.TZ = "UTC"
	}
	for _, u := range []struct{ key, v string }{{"images", f.Spec.Updates.Images}, {"host", f.Spec.Updates.Host}} {
		if u.v != "" && !slices.Contains(updatePolicies, u.v) {
			return nil, fmt.Errorf("fleet.yaml: spec.updates.%s must be off, notify or auto, got %q", u.key, u.v)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(f.Spec.Notifications.Channels)) {
		c := f.Spec.Notifications.Channels[name]
		switch {
		case !nameRe.MatchString(name):
			return nil, fmt.Errorf("fleet.yaml: notifications.channels.%s: a name is lowercase letters, digits, - and _", name)
		case (c.URL == "") == (c.URLSecret == ""):
			return nil, fmt.Errorf("fleet.yaml: notifications.channels.%s: set urlSecret (a key in fleet.secret.yaml) or url", name)
		case c.Format != "" && c.Format != "text" && c.Format != "json":
			return nil, fmt.Errorf("fleet.yaml: notifications.channels.%s: format is text or json", name)
		case c.SigningSecret != "" && c.Format != "json":
			return nil, fmt.Errorf("fleet.yaml: notifications.channels.%s: signingSecret needs format: json", name)
		}
	}
	for i, r := range f.Spec.Notifications.Routes {
		if len(r.Channels) == 0 {
			return nil, fmt.Errorf("fleet.yaml: notifications.routes[%d]: channels is required", i)
		}
		for _, c := range r.Channels {
			if _, ok := f.Spec.Notifications.Channels[c]; !ok {
				return nil, fmt.Errorf("fleet.yaml: notifications.routes[%d]: unknown channel %q", i, c)
			}
		}
		if r.MinSeverity != "" && !slices.Contains([]string{"info", "warning", "error"}, r.MinSeverity) {
			return nil, fmt.Errorf("fleet.yaml: notifications.routes[%d]: minSeverity is info, warning or error", i)
		}
	}
	if err := checkEgress(f.Spec.Egress); err != nil {
		return nil, fmt.Errorf("fleet.yaml: spec.egress: %w", err)
	}
	for i := range f.Spec.UptimeKuma {
		k := &f.Spec.UptimeKuma[i]
		if k.RollingUpdates == "" {
			k.RollingUpdates = "incident"
		}
		if !slices.Contains([]string{"incident", "maintenance", "none"}, k.RollingUpdates) {
			return nil, fmt.Errorf("fleet.yaml: spec.uptimeKuma[%d].rollingUpdates must be incident, maintenance or none", i)
		}
	}
	for i, m := range f.Spec.Mirrors {
		// Passed to git: an option-like or blank URL must not get there.
		if m == "" || strings.HasPrefix(m, "-") || strings.ContainsAny(m, " \t\n") {
			return nil, fmt.Errorf("fleet.yaml: spec.mirrors[%d]: %q is not a git URL", i, m)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(f.Spec.Paths)) {
		p := f.Spec.Paths[name]
		switch {
		case !nameRe.MatchString(name):
			return nil, fmt.Errorf("fleet.yaml: spec.paths.%s: a name is lowercase letters, digits, - and _", name)
		case !filepath.IsAbs(p) || p != filepath.Clean(p):
			return nil, fmt.Errorf("fleet.yaml: spec.paths.%s: %q must be a clean absolute path (%s)", name, p, filepath.Clean(p))
		}
	}
	seen := map[string]bool{}
	for _, s := range f.Spec.TemplateSources {
		if !nameRe.MatchString(s.Name) || seen[s.Name] {
			return nil, fmt.Errorf("fleet.yaml: template source name %q is invalid or duplicated", s.Name)
		}
		seen[s.Name] = true
		if (s.URL == "") == (s.Path == "") {
			return nil, fmt.Errorf("fleet.yaml: template source %q needs exactly one of url or path", s.Name)
		}
	}
	return &f, nil
}

// Source returns the named template source.
func (f *Fleet) Source(name string) (Source, bool) {
	for _, s := range f.Spec.TemplateSources {
		if s.Name == name {
			return s, true
		}
	}
	return Source{}, false
}

// StackDirs are the directories stacks live in, in apply order: system
// stacks (ingress, logs...) before apps.
var StackDirs = []string{"system", "stacks"}

// LoadStack reads one stack by name.
func (f *Fleet) LoadStack(name string) (*Stack, error) {
	for _, d := range StackDirs {
		dir := filepath.Join(f.Dir, d, name)
		if _, err := os.Stat(filepath.Join(dir, "stack.yaml")); err == nil {
			return loadStack(dir)
		}
	}
	return nil, fmt.Errorf("no stack %q in %v", name, StackDirs)
}

// Stacks reads every stack, system stacks first, each group sorted by name.
func (f *Fleet) Stacks() ([]*Stack, error) {
	var out []*Stack
	seen := map[string]string{}
	for _, d := range StackDirs {
		entries, err := os.ReadDir(filepath.Join(f.Dir, d))
		if errors.Is(err, os.ErrNotExist) {
			continue
		} else if err != nil {
			return nil, err
		}
		for _, e := range entries {
			if !e.IsDir() {
				continue
			}
			dir := filepath.Join(f.Dir, d, e.Name())
			if _, err := os.Stat(filepath.Join(dir, "stack.yaml")); err != nil {
				continue
			}
			s, err := loadStack(dir)
			if err != nil {
				return nil, err
			}
			if prev, dup := seen[s.Metadata.Name]; dup {
				return nil, fmt.Errorf("stack %q exists in both %s and %s", s.Metadata.Name, prev, d)
			}
			seen[s.Metadata.Name] = d
			out = append(out, s)
		}
	}
	return out, nil
}

func loadStack(dir string) (*Stack, error) {
	var s Stack
	path := filepath.Join(dir, "stack.yaml")
	if err := decodeStrict(path, &s); err != nil {
		return nil, err
	}
	s.Dir = dir
	var errs []error
	bad := func(format string, a ...any) { errs = append(errs, fmt.Errorf(path+": "+format, a...)) }
	if s.Kind != "Stack" {
		bad("kind must be Stack")
	}
	if s.APIVersion != APIVersion {
		bad("apiVersion must be %q, got %q", APIVersion, s.APIVersion)
	}
	if s.Metadata.Name != filepath.Base(dir) || !nameRe.MatchString(s.Metadata.Name) {
		bad("metadata.name %q must be a valid name equal to the directory name", s.Metadata.Name)
	}
	if s.Spec.Target == "" {
		bad("spec.target is required (a host name, or local)")
	}
	if err := checkEgress(s.Spec.Egress); err != nil {
		bad("spec.egress: %v", err)
	}
	if s.Spec.Mode == "" {
		s.Spec.Mode = "compose"
	}
	if !slices.Contains(modes, s.Spec.Mode) {
		bad("spec.mode must be compose or swarm")
	}
	if s.Spec.Apply == "" {
		s.Spec.Apply = "manual"
	}
	if !slices.Contains(applyPolicies, s.Spec.Apply) {
		bad("spec.apply must be manual or auto")
	}
	if s.Spec.Updates == "" {
		s.Spec.Updates = "notify"
	}
	if !slices.Contains(updatePolicies, s.Spec.Updates) {
		bad("spec.updates must be off, notify or auto")
	}
	if s.Spec.Snapshot == "" {
		s.Spec.Snapshot = "auto"
	}
	if !slices.Contains(snapshotModes, s.Spec.Snapshot) {
		bad("spec.snapshot must be auto or off")
	}
	if t := s.Spec.Template; t != nil && (t.Source == "" || t.Name == "") {
		bad("spec.template needs source and name")
	}
	if s.Spec.Template == nil {
		if _, err := os.Stat(filepath.Join(dir, "compose.yaml")); err != nil {
			bad("a stack without spec.template needs a compose.yaml")
		}
	}
	return &s, errors.Join(errs...)
}

// ResolvePath turns a path input value into a host path: @name refers to
// spec.paths, anything else is returned as it is.
func (f *Fleet) ResolvePath(v string) (string, error) {
	name, ok := strings.CutPrefix(v, "@")
	if !ok {
		return v, nil
	}
	p, ok := f.Spec.Paths[name]
	if !ok {
		return "", fmt.Errorf("@%s is not defined in fleet.yaml spec.paths", name)
	}
	return p, nil
}
