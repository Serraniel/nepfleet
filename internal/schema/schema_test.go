// TestCommittedSchemasAreCurrent fails when a Go type changed but schemas/
// was not regenerated.
func TestCommittedSchemasAreCurrent(t *testing.T) {
	files, err := All("../..")
	if err != nil {
		t.Fatal(err)
	}
	for name, want := range files {
		got, err := os.ReadFile(filepath.Join("../../schemas", name))
		if err != nil || !bytes.Equal(got, want) {
			t.Errorf("schemas/%s is out of date: run go run ./tools/schema", name)
		}
	}
	entries, _ := os.ReadDir("../../schemas")
	for _, e := range entries {
		if _, ok := files[e.Name()]; !ok {
			t.Errorf("schemas/%s is not generated by anything; remove it", e.Name())
		}
	}
}

// The schemas must accept what NepFleet writes and parses, and reject what
// the parser rejects.
func TestSchemasAgreeWithParser(t *testing.T) {
	files, err := All("../..")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	if err := fleet.Init(dir); err != nil {
		t.Fatal(err)
	}
	fleetYAML, err := os.ReadFile(filepath.Join(dir, "fleet.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	tplYAML, err := os.ReadFile("../template/testdata/demo/template.yaml")
	if err != nil {
		t.Fatal(err)
	}
	stackYAML := "apiVersion: nepfleet/v1alpha1\nkind: Stack\nmetadata: {name: web}\nspec:\n  target: local\n  template: {source: official, name: whoami, version: 1.0.0}\n  values: {DOMAIN: example.org}\n"

	for _, c := range []struct {
		schema, doc string
		ok          bool
	}{
		{"fleet.schema.json", string(fleetYAML), true},
		{"fleet.schema.json", string(fleetYAML) + "surprise: true\n", false},
		{"fleet.schema.json", strings.Replace(string(fleetYAML), "images: notify", "images: sometimes", 1), false},
		{"stack.schema.json", stackYAML, true},
		{"stack.schema.json", strings.Replace(stackYAML, "  target: local\n", "", 1), false},
		{"stack.schema.json", stackYAML + "  mode: kubernetes\n", false},
		{"stack.schema.json", strings.Replace(stackYAML, "kind: Stack", "kind: Fleet", 1), false},
		{"template.schema.json", string(tplYAML), true},
		{"template.schema.json", strings.Replace(string(tplYAML), "tier: ", "tier: x", 1), false},
	} {
		var schema, doc any
		if err := json.Unmarshal(files[c.schema], &schema); err != nil {
			t.Fatal(err)
		}
		if err := yaml.Unmarshal([]byte(c.doc), &doc); err != nil {
			t.Fatal(err)
		}
		err := validate(schema.(map[string]any), doc, "")
		if (err == nil) != c.ok {
			t.Errorf("%s: want ok=%v, got %v for\n%s", c.schema, c.ok, err, c.doc)
		}
	}
}

// validate checks the subset of JSON Schema the generator emits.
func validate(s map[string]any, v any, at string) error {
	if c, ok := s["const"]; ok && fmt.Sprint(v) != c {
		return fmt.Errorf("%s: want %v", at, c)
	}
	if e, ok := s["enum"].([]any); ok && !slices.ContainsFunc(e, func(x any) bool { return x == fmt.Sprint(v) }) {
		return fmt.Errorf("%s: %v not in %v", at, v, e)
	}
	if p, ok := s["pattern"].(string); ok && !regexp.MustCompile(p).MatchString(fmt.Sprint(v)) {
		return fmt.Errorf("%s: %v does not match %s", at, v, p)
	}
	switch s["type"] {
	case "object":
		m, ok := v.(map[string]any)
		if !ok {
			return fmt.Errorf("%s: want an object", at)
		}
		props, _ := s["properties"].(map[string]any)
		for _, r := range asSlice(s["required"]) {
			if _, ok := m[r.(string)]; !ok {
				return fmt.Errorf("%s: %s is required", at, r)
			}
		}
		for k, val := range m {
			sub, known := props[k].(map[string]any)
			if !known {
				if ap, ok := s["additionalProperties"].(map[string]any); ok {
					sub = ap
				} else if s["additionalProperties"] == false {
					return fmt.Errorf("%s: unknown field %s", at, k)
				} else {
					continue
				}
			}
			if err := validate(sub, val, at+"."+k); err != nil {
				return err
			}
		}
	case "array":
		for i, item := range asSlice(v) {
			if err := validate(s["items"].(map[string]any), item, fmt.Sprintf("%s[%d]", at, i)); err != nil {
				return err
			}
		}
	case "string":
		if _, ok := v.(string); !ok {
			return fmt.Errorf("%s: want a string, got %T", at, v)
		}
	}
	return nil
}

func asSlice(v any) []any { s, _ := v.([]any); return s }
